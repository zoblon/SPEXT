import AppKit

/// A complete in-memory copy of every materialized item representation.
private struct PasteboardSnapshot {
    let items: [[NSPasteboard.PasteboardType: Data]]

    static func capture(from board: NSPasteboard) -> PasteboardSnapshot? {
        let count = board.changeCount
        var items: [[NSPasteboard.PasteboardType: Data]] = []
        var bytes = 0
        for item in board.pasteboardItems ?? [] {
            var representations: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                // Never overwrite a clipboard that cannot be backed up completely.
                guard let data = item.data(forType: type), data.count <= 64 * 1024 * 1024 - bytes else { return nil }
                bytes += data.count
                representations[type] = data
            }
            items.append(representations)
        }
        guard board.changeCount == count else { return nil }
        return PasteboardSnapshot(items: items)
    }

    func restore(to board: NSPasteboard, ownedChangeCount: Int) {
        let restored: [NSPasteboardItem] = items.map { representations in
            let item = NSPasteboardItem()
            for (type, data) in representations { item.setData(data, forType: type) }
            return item
        }
        guard board.changeCount == ownedChangeCount else { return }
        board.clearContents()
        if !restored.isEmpty { board.writeObjects(restored) }
    }
}

/// Pasteboard data requests can arrive outside the service's main-queue polling.
private final class ClipboardReadTracker: @unchecked Sendable {
    private let lock = NSLock()
    private var lastRead: TimeInterval?
    func record(_ time: TimeInterval) { lock.lock(); lastRead = time; lock.unlock() }
    func latest() -> TimeInterval? { lock.lock(); defer { lock.unlock() }; return lastRead }
}

private final class ClipboardTextProvider: NSObject, NSPasteboardItemDataProvider {
    let text: String
    let tracker: ClipboardReadTracker
    let now: () -> TimeInterval

    init(text: String, tracker: ClipboardReadTracker, now: @escaping () -> TimeInterval) {
        self.text = text; self.tracker = tracker; self.now = now
    }

    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem,
                    provideDataForType type: NSPasteboard.PasteboardType) {
        guard type == .string else { return }
        tracker.record(now())
        item.setString(text, forType: .string)
    }
}

/// Holds original clipboard data only until the owned automatic-paste session ends.
/// A read is a timing heuristic; it does not prove a target field accepted the text.
final class ClipboardRestoreService {
    struct Ticket: Equatable { let id: UUID; let changeCount: Int }
    private struct Session {
        let ticket: Ticket
        let original: PasteboardSnapshot
        let item: NSPasteboardItem
        let provider: ClipboardTextProvider
        var triggeredAt: TimeInterval?
    }

    private let pasteboard: NSPasteboard
    private let now: () -> TimeInterval
    private let automaticallyPoll: Bool
    private var session: Session?
    private var scheduled: DispatchWorkItem?
    private var quitObserver: NSObjectProtocol?

    init(pasteboard: NSPasteboard = .general,
         now: @escaping () -> TimeInterval = { ProcessInfo.processInfo.systemUptime },
         automaticallyPoll: Bool = true) {
        self.pasteboard = pasteboard; self.now = now; self.automaticallyPoll = automaticallyPoll
        quitObserver = NotificationCenter.default.addObserver(
            forName: NSApplication.willTerminateNotification, object: nil, queue: .main
        ) { [weak self] _ in self?.finishOnQuit() }
    }

    deinit {
        scheduled?.cancel()
        if let quitObserver { NotificationCenter.default.removeObserver(quitObserver) }
    }

    func prepare(text: String) -> Ticket? {
        scheduled?.cancel(); scheduled = nil
        let expectedCount = pasteboard.changeCount
        let original: PasteboardSnapshot
        if let previous = session, owns(previous.ticket) {
            original = previous.original
        } else {
            guard let captured = PasteboardSnapshot.capture(from: pasteboard) else {
                session = nil
                return nil
            }
            original = captured
        }
        let tracker = ClipboardReadTracker()
        let provider = ClipboardTextProvider(text: text, tracker: tracker, now: now)
        let item = NSPasteboardItem()
        guard item.setDataProvider(provider, forTypes: [.string]) else { return nil }
        item.setData(Data(), forType: .init("org.nspasteboard.TransientType"))
        item.setData(Data(), forType: .init("org.nspasteboard.ConcealedType"))
        item.setData(Data(), forType: .init("org.nspasteboard.AutoGeneratedType"))
        guard pasteboard.changeCount == expectedCount else { clearSession(); return nil }
        pasteboard.prepareForNewContents(with: .currentHostOnly)
        let ownedCount = pasteboard.changeCount
        guard pasteboard.writeObjects([item]) else {
            original.restore(to: pasteboard, ownedChangeCount: ownedCount)
            session = nil
            return nil
        }
        let ticket = Ticket(id: UUID(), changeCount: pasteboard.changeCount)
        session = Session(ticket: ticket, original: original, item: item, provider: provider)
        return ticket
    }

    func owns(_ ticket: Ticket) -> Bool {
        session?.ticket == ticket && pasteboard.changeCount == ticket.changeCount
    }

    func didTriggerPaste(_ ticket: Ticket) {
        guard owns(ticket) else { return }
        session?.triggeredAt = now()
        schedulePoll()
    }

    func keepForManualPaste(_ ticket: Ticket) {
        guard owns(ticket), let session else { return }
        // Materialize the promise before releasing its provider, including on quit.
        pasteboard.setString(session.provider.text, forType: .string)
        clearSession()
    }

    func poll() {
        guard let current = session else { return }
        guard owns(current.ticket) else { clearSession(); return }
        guard let started = current.triggeredAt else { return }
        let time = now()
        let elapsed = time - started
        let lastRead = current.provider.tracker.latest()
        let quietAfterRead = lastRead.map { time - $0 >= 0.5 } ?? false
        let due = elapsed >= 15 || (lastRead == nil && elapsed >= 5)
            || (elapsed >= 1 && quietAfterRead)
        guard due else { return }
        current.original.restore(to: pasteboard, ownedChangeCount: current.ticket.changeCount)
        clearSession()
    }

    func finishOnQuit() {
        if let current = session, owns(current.ticket) {
            if current.triggeredAt != nil {
                current.original.restore(to: pasteboard, ownedChangeCount: current.ticket.changeCount)
            } else {
                pasteboard.setString(current.provider.text, forType: .string)
            }
        }
        clearSession()
    }

    private func clearSession() {
        scheduled?.cancel(); scheduled = nil; session = nil
    }

    private func schedulePoll() {
        guard automaticallyPoll, session?.triggeredAt != nil else { return }
        scheduled?.cancel()
        let work = DispatchWorkItem { [weak self] in
            self?.poll()
            self?.schedulePoll()
        }
        scheduled = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.1, execute: work)
    }
}
